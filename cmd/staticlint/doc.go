// staticlint — статический анализатор Go-кода проекта metrics.
//
// # Описание
//
// staticlint объединяет набор встроенных и пользовательских анализаторов
// пакета golang.org/x/tools/go/analysis и запускает их через multichecker.
// Конфигурация анализаторов читается из файла config.yaml.
//
// # Состав анализаторов
//
// Встроенные (golang.org/x/tools):
//
//   - printf    — проверка соответствия аргументов форматным глаголам Printf-функций;
//   - shadow    — обнаружение затенения переменных;
//   - structtag — проверка корректности тегов struct.
//
// Внешние:
//
//   - errcheck  (github.com/kisielk/errcheck) — обнаружение непроверенных ошибок;
//   - nilaway   (go.uber.org/nilaway)         — обнаружение потенциальных nil-паник;
//   - staticcheck (honnef.co/go/tools/staticcheck) — набор SA/ST/S/Q-проверок,
//     подключаемых по конфигурации (см. ниже).
//
// Пользовательские:
//
//   - noosexit  (github.com/postman17/metrics/cmd/staticlint/analyzers) — запрещает
//     прямой вызов os.Exit в функции main пакета main (см. пакет analyzers).
//
// # Конфигурация
//
// Файл config.yaml ищется в следующем порядке:
//
//  1. В директории рядом с исполняемым файлом (os.Executable).
//  2. В текущей рабочей директории.
//
// Формат файла:
//
//	check_prefix: "SA"          # префикс имён анализаторов staticcheck для включения
//	static_check:               # точечный список дополнительных анализаторов staticcheck
//	  - "S1000"
//	  - "ST1003"
//	  - "ST1023"
//
// Поля:
//   - check_prefix — анализаторы staticcheck, чьё имя начинается с этого префикса,
//     будут добавлены автоматически (например, "SA" включает все SA****).
//   - static_check — точечный список имён анализаторов, добавляемых дополнительно
//     (для тех, чей префикс не совпадает с check_prefix).
//
// nilaway исключает ложные срабатывания из стандартной библиотеки и зависимостей
// (compress/gzip, go/ast, go/parser, go/printer, go/types, go/doc,
// go.uber.org/nilaway, golang.org/x/tools) через флаг exclude-pkgs.
//
// # Запуск
//
// Из корня проекта:
//
//	go run ./cmd/staticlint ./...
//
// Через Makefile:
//
//	make check
//
// На отдельный пакет:
//
//	go run ./cmd/staticlint ./cmd/server/...
//
// # Коды завершения
//
//   - 0 — нарушений не найдено;
//   - 1 — нарушение найдено (анализатор вернул диагностику);
//   - 3 — ошибка инициализации или сборки пакета.
